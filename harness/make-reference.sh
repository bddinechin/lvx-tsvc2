# Regenerate the committed correctness references from NATIVE x86 builds.
#
#   ./harness/make-reference.sh
#   ITER=1 LEN1D=32000 ./harness/make-reference.sh
#
# Writes harness/reference-<iter>-<len1d>-<len2d>-<type>.tsv, one line per loop:
# the loop name and its checksum BIT PATTERN.
#
# WHY GENERATED NATIVELY, not recorded from an LVX run: a reference taken from
# the target cannot detect a target miscompile, only perpetuate one.
# lvx-polybench's reference-output/ is built the same way and for the same
# reason.
#
# WHY THE SETTINGS ARE IN THE FILENAME, and this is the part specific to TSVC:
# most of its loops ACCUMULATE across the nl loop, so the checksum is a
# function of `iterations' as well as of the code. s1221's
# `b[i] = b[i-4] + a[i]' run 100000 times is not the same computation as run
# once. A reference is therefore only valid for the exact (iterations, LEN_1D,
# LEN_2D, type) it was generated at, and a filename that says so is cheaper
# than a mismatch nobody can explain. It also means these checksums are NOT
# comparable with upstream TSVC's published figures.
#
# The checksum is compared as a BIT PATTERN. A decimal rendering of a float is
# a lossy comparison, and this is the oracle.
set -u

here="$(cd "$(dirname "$0")" && pwd)"
repo="$(dirname "$here")"

ITER=${ITER:-1}
LEN1D=${LEN1D:-32000}
LEN2D=${LEN2D:-256}
TYPES=${TYPE:-"float double"}

tmp=$(mktemp -d); trap 'rm -rf "$tmp"' 0 1 2 3 15
rc=0
for type in $TYPES; do
    case "$type" in float|double) ;; *) echo "TYPE must be float or double" >&2; exit 2 ;; esac
    tmacro=""; [ "$type" = double ] && tmacro="-DTSVC_DOUBLE"
    out="$here/reference-$ITER-$LEN1D-$LEN2D-$type.tsv"

    # -O2 and no -ffast-math: the reference must be the straightforward
    # evaluation, not one the host compiler was licensed to reassociate. The
    # LVX side may use -ffast-math; what matters is that the oracle does not.
    cc -O2 -I"$repo/src" -Diterations="$ITER" -DLEN_1D="$LEN1D" -DLEN_2D="$LEN2D" $tmacro \
       -o "$tmp/tsvc-$type" "$repo/src/tsvc.c" "$repo/src/common.c" "$repo/src/dummy.c" \
       "$repo/lvx/tsvc-report.c" -lm 2>"$tmp/err-$type" || {
        echo "native build failed ($type):" >&2; sed -n '1,6p' "$tmp/err-$type" >&2; rc=1; continue; }

    {
        printf '# GENERATED by harness/make-reference.sh from the native x86 build.\n'
        printf '# iterations=%s LEN_1D=%s LEN_2D=%s type=%s\n' "$ITER" "$LEN1D" "$LEN2D" "$type"
        printf '# loop\tchecksum_bits\n'
        "$tmp/tsvc-$type" 2>/dev/null | awk -F'\t' '
            /^RESULT/ { loop=$2; for (i=3;i<=NF;i++) if ($i ~ /^checksum_bits /) { sub(/^checksum_bits /,"",$i); print loop "\t" $i } }'
    } > "$tmp/out-$type"

    n=$(grep -vc '^#' "$tmp/out-$type")
    if [ "$n" -lt 100 ]; then
        echo "only $n loops reported for $type -- expected ~151, not writing" >&2; rc=1; continue
    fi
    mv "$tmp/out-$type" "$out"
    printf '  %-7s %s loops -> %s\n' "$type" "$n" "$(basename "$out")"
done
[ "$rc" = 0 ] || exit 1
echo
echo "references are valid ONLY for iterations=$ITER LEN_1D=$LEN1D LEN_2D=$LEN2D"
